import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { transformSync } from 'esbuild'

const root = fileURLToPath(new URL('../', import.meta.url))
const srcDir = path.join(root, 'src', 'client')
const outFile = path.join(root, 'lib', 'client.js')

const files = [
  'constants.js',
  'request.js',
  'locales.js',
  'locales-adoption.js',
  'locales-overview.js',
  'chevron.js',
  'styles.js',
  'error-boundary.js',
  'progress-bar.js',
  'quota-forecast.js',
  'components/update-panel.js',
  'components/key-section.js',
  'components/key-discovery.js',
  'components/accounts-section.js',
  'components/proxy-section.js',
  'components/quota-section.js',
  'token-count.js',
  'components/model-tools.js',
  'components/upstream-settings.js',
  'components/models-section.js',
  'components/native-model-editor.js',
  'components/upstream-observation.js',
  'components/stats-insights.js',
  'components/stats-filters.js',
  'components/stats-breakdown.js',
  'components/stats-section.js',
  'components/analytics.js',
  'components/economy-settings.js',
  'components/diag-section.js',
  'usage-surfaces.js',
  'components/display-settings.js',
  'components/model-probe.js',
  'components/search-settings.js',
  'settings-page.js',
  'plugin-card.js',
  'entry.js',
]

const parts = files.map((rel) => {
  // 先替换再压缩：h 作为未绑定的全局引用，esbuild 不会把局部变量重命名为 h 而遮蔽它。
  const code = readFileSync(path.join(srcDir, rel), 'utf8').replaceAll('React.createElement(', 'h(')
  const { code: compact } = transformSync(code, { sourcefile: rel, loader: 'js', target: 'es2022', minifyWhitespace: true, minifyIdentifiers: true, minifySyntax: false, legalComments: 'none' })
  // 商店限制 256 KiB：只压缩局部标识符（各文件顶层声明保持原样，供跨文件引用），
  // 并把 React.createElement( 统一写作 h(。可读源码随包发布在 src/client/。
  return `// --- src/client/${rel} ---\n` + compact.trim()
})

const bundle = `// @generated by scripts/build-client.js - DO NOT EDIT DIRECTLY.
// Edit modular source files in src/client/ instead.

window.__ModuleLoader__.load({
  id: ${JSON.stringify(JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8')).name)},
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    let React = require('react')
    const h = React.createElement

${parts.join('\n\n')}

    return module.exports
  },
})
`

const size = Buffer.byteLength(bundle)
const check = process.argv.includes('--check')
if (check) {
  if (readFileSync(outFile, 'utf8') !== bundle) {
    console.error('[build-client] lib/client.js is stale. Run npm run build:client.')
    process.exit(1)
  }
} else {
  writeFileSync(outFile, bundle, 'utf8')
}
console.log(`[build-client] ${check ? 'Checked' : 'Rebuilt'} lib/client.js: ${size} bytes (< 256 KiB limit)`)

if (size > 262144) {
  console.error('[build-client] ERROR: lib/client.js exceeds official DSH Store limit (262144 bytes)!')
  process.exit(1)
}

try {
  execFileSync(process.execPath, ['--check', outFile], { stdio: 'inherit' })
  console.log('[build-client] Syntax check: OK')
} catch (err) {
  console.error('[build-client] Syntax error in assembled lib/client.js!')
  process.exit(1)
}
